export const FAMILY_STRINGS = {
  "en-IN": en,
  "hi-IN": hi,
  "bn-IN": bn,
  "gu-IN": gu,
  "kn-IN": kn,
  "ml-IN": ml,
  "mr-IN": mr,
  "od-IN": od,
  "pa-IN": pa,
  "ta-IN": ta,
  "te-IN": te,
};

export const ENGLISH_FAMILY_STRINGS = en;

/** The language code the family screens show: the family's choice, or the record's on "auto" or unset. */
export const familyLanguageCode = (languageCode, fallbackCode) => {
  const code = languageCode === AUTO_LANGUAGE || !languageCode ? fallbackCode : languageCode;
  return FAMILY_STRINGS[code] ? code : "en-IN";
};

/** The family screens' words in a language. Any key a language lacks comes from English. */
export const familyStrings = (languageCode, fallbackCode) => ({
  ...en,
  ...FAMILY_STRINGS[familyLanguageCode(languageCode, fallbackCode)],
});

/** Fills "{name}" placeholders. A placeholder with no value is left out rather than shown raw. */
export const fill = (text, vars = {}) => String(text).replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? ""));

/** "{a} and {b}" split into text and the named values, so a value can be a React element. */
export const fillParts = (text, vars = {}) =>
  String(text)
    .split(/(\{\w+\})/)
    .filter(Boolean)
    .map((part) => {
      const match = /^\{(\w+)\}$/.exec(part);
      return match ? (vars[match[1]] ?? "") : part;
    });

/** A locale for dates in this language. Odia's standard code is "or", not "od". */
export const familyDateLocale = (code) => (code === "od-IN" ? "or-IN" : code || "en-IN");
