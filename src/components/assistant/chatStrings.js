/**
 * The chat's words in a language. On "auto" (answer in the language I use) the screen follows the
 * language on the patient's record, which is the best guess before they have said anything.
 * Any key a language lacks comes from English.
 */
export const chatStrings = (languageCode, fallbackCode) => {
  const code = languageCode === AUTO_LANGUAGE || !languageCode ? fallbackCode : languageCode;
  return { ...en, ...CHAT_STRINGS[code] };
};

/** The lang attribute for text shown from chatStrings(languageCode, fallbackCode). */
export const chatStringsLang = (languageCode, fallbackCode) => {
  const code = languageCode === AUTO_LANGUAGE || !languageCode ? fallbackCode : languageCode;
  return CHAT_STRINGS[code] ? code : "en-IN";
};
